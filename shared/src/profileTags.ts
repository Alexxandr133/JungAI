export type ProfileTag = (typeof PROFILE_TAGS)[number];

/** Топ-8 для чипов клиентского лендинга (S2) */
export const LANDING_TOPIC_TAGS = PROFILE_TAGS.slice(0, 8) as readonly ProfileTag[];

/** Темы в мастере подбора — короткий срез, не весь словарь */
export const MATCH_TOPIC_TAGS = PROFILE_TAGS.slice(0, 16) as readonly ProfileTag[];

/** Подсказки в редакторе, когда поиск пуст */
export const PROFILE_TAG_SUGGESTIONS = PROFILE_TAGS.slice(0, 12) as readonly ProfileTag[];

export function isProfileTag(value: string): value is ProfileTag {
  return (PROFILE_TAGS as readonly string[]).includes(value);
}

export function searchProfileTags(query: string, limit = 24): ProfileTag[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const scored: { tag: ProfileTag; score: number }[] = [];
  for (const tag of PROFILE_TAGS) {
    const lower = tag.toLowerCase();
    if (lower === q) scored.push({ tag, score: 0 });
    else if (lower.startsWith(q)) scored.push({ tag, score: 1 });
    else if (lower.includes(q)) scored.push({ tag, score: 2 });
  }
  scored.sort((a, b) => a.score - b.score || a.tag.localeCompare(b.tag, 'ru'));
  return scored.slice(0, limit).map((s) => s.tag);
}
